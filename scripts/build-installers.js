#!/usr/bin/env node
/** GitHub Release へ添付する「ダブルクリックで入る」インストーラーを組み立てる。
 *
 * プラグイン本体には何も焼かない（src/studio-plugin.js の冒頭を参照）ので、リリースの
 * ときに一度組み立てて base64 でスクリプトへ埋め込める。インストール時に通信しないぶん、
 * 社内プロキシの向こうでも動くし、URL が腐りようもない。
 *
 * 置き先は `rosheet plugin` と同じファイル名にしてある。名前を変えると、CLI で入れた人が
 * インストーラーも使ったときに、同じプラグインが 2 つ読み込まれる。
 */

const fs = require("fs");
const path = require("path");

const { buildPlugin, DEFAULT_PLUGIN_FILE } = require("../src/studio-plugin");

// スクリプト本文と base64 の境目。インストーラーは自分自身をこの行で切って、後ろを
// decode する。行全体がこの文字列と一致する行は、ファイル中に 1 本だけ。
const PAYLOAD_MARKER = "#ROSHEET_RBXMX_BASE64#";

const WINDOWS_INSTALLER_NAME = "rosheet-plugin-installer-windows.cmd";
const MACOS_INSTALLER_NAME = "rosheet-plugin-installer-macos.command";
const MACOS_ARCHIVE_NAME = "rosheet-plugin-installer-macos.zip";

function base64Lines(payload) {
	return payload.toString("base64").match(/.{1,76}/g) || [];
}

// PowerShell は 1 行の -Command で呼ぶ。スクリプトファイルを介さないので実行ポリシーに
// 引っかからず、二重引用符の入れ子も避けられる。
const WINDOWS_POWERSHELL = [
	"$ErrorActionPreference='Stop';",
	// %~f0 は環境変数で渡す。PowerShell の引数へ直接埋めると、パスに空白や引用符が
	// 混ざったときに壊れる。
	"$text=[IO.File]::ReadAllText($env:ROSHEET_SELF);",
	"$marker='" + PAYLOAD_MARKER + "';",
	// LastIndexOf。この行自身にもマーカーの文字列が出るので、最後の 1 個を取る。
	"$payload=$text.Substring($text.LastIndexOf($marker)+$marker.Length);",
	"$dir=Join-Path $env:LOCALAPPDATA 'Roblox\\Plugins';",
	"[void][IO.Directory]::CreateDirectory($dir);",
	"$file=Join-Path $dir '" + DEFAULT_PLUGIN_FILE + "';",
	"[IO.File]::WriteAllBytes($file,[Convert]::FromBase64String(($payload -replace '\\s','')));",
	"Write-Host ('  Installed: '+$file)",
].join("");

function buildWindowsInstaller(payload) {
	const lines = [
		"@echo off",
		"rem rosheet Studio plugin installer for Windows.",
		"rem Generated by scripts/build-installers.js - do not edit by hand.",
		"rem The plugin itself is the base64 block below the marker line at the bottom.",
		"setlocal",
		'set "ROSHEET_SELF=%~f0"',
		"echo.",
		"echo   rosheet Studio plugin installer",
		"echo.",
		'powershell -NoProfile -ExecutionPolicy Bypass -Command "' + WINDOWS_POWERSHELL + '"',
		"if errorlevel 1 (",
		"\techo.",
		"\techo   Installation failed. See the error above.",
		") else (",
		"\techo.",
		"\techo   Restart Roblox Studio, then open Plugins ^> rosheet.",
		")",
		"echo.",
		"pause",
		"exit /b",
		PAYLOAD_MARKER,
		...base64Lines(payload),
		"",
	];

	// cmd.exe は LF だけのバッチでも大抵動くが、括弧ブロックやラベルで崩れることがある。
	// 生成側で CRLF に揃えておく。
	return lines.join("\r\n");
}

function buildMacInstaller(payload) {
	const lines = [
		"#!/bin/bash",
		"# rosheet Studio plugin installer for macOS.",
		"# Generated by scripts/build-installers.js - do not edit by hand.",
		"# The plugin itself is the base64 block below the marker line at the bottom.",
		"set -euo pipefail",
		"",
		'self="${BASH_SOURCE[0]}"',
		'dir="$HOME/Documents/Roblox/Plugins"',
		'file="$dir/' + DEFAULT_PLUGIN_FILE + '"',
		"",
		'echo ""',
		'echo "  rosheet Studio plugin installer"',
		'echo ""',
		"",
		'mkdir -p "$dir"',
		"",
		"# macOS 標準の base64 は -D、GNU coreutils は -d。試してから決める。",
		"if printf 'cm9zaGVldA==' | base64 -D >/dev/null 2>&1; then",
		"\tdecode=(base64 -D)",
		"else",
		"\tdecode=(base64 -d)",
		"fi",
		"",
		// awk の正規表現は行頭行末で留めてある。プログラムを書いているこの行自体は
		// マーカーだけの行ではないので、自分に引っかからない。
		"awk 'payload; /^" + PAYLOAD_MARKER + "$/ { payload = 1 }' \"$self\" | \"${decode[@]}\" > \"$file\"",
		"",
		'echo "  Installed: $file"',
		'echo ""',
		'echo "  Restart Roblox Studio, then open Plugins > rosheet."',
		'echo ""',
		"",
		// ここで抜けないと、bash が下の base64 をコマンドとして読みはじめる。
		"exit 0",
		PAYLOAD_MARKER,
		...base64Lines(payload),
		"",
	];

	return lines.join("\n");
}

function crc32(buffer) {
	let crc = ~0;
	for (const byte of buffer) {
		crc ^= byte;
		for (let bit = 0; bit < 8; bit++) {
			crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
		}
	}

	return ~crc >>> 0;
}

/** GitHub Release のアセットにはパーミッションが残らない。実行ビットの落ちた .command は
 * ダブルクリックすると "could not be executed" になるので、mac 側だけ zip に包んで配る。
 *
 * zip コマンドには頼らない。Windows の開発機には大抵入っておらず、代わりの Compress-Archive
 * は実行ビットを落とす —— ここで欲しいものそのものを。無圧縮 1 ファイルの zip は自前で
 * 書けるほど小さい。
 */
function createZip(entries) {
	const locals = [];
	const centrals = [];
	let offset = 0;

	for (const entry of entries) {
		const name = Buffer.from(entry.name, "utf8");
		const crc = crc32(entry.data);

		const local = Buffer.alloc(30);
		local.writeUInt32LE(0x04034b50, 0);
		local.writeUInt16LE(20, 4); // version needed
		local.writeUInt16LE(0, 6); // flags
		local.writeUInt16LE(0, 8); // method: store
		// タイムスタンプは 1980-01-01 に固定する。同じ入力からは同じ zip が出る。
		local.writeUInt16LE(0, 10); // time
		local.writeUInt16LE(0x0021, 12); // date
		local.writeUInt32LE(crc, 14);
		local.writeUInt32LE(entry.data.length, 18);
		local.writeUInt32LE(entry.data.length, 22);
		local.writeUInt16LE(name.length, 26);
		local.writeUInt16LE(0, 28); // extra

		const central = Buffer.alloc(46);
		central.writeUInt32LE(0x02014b50, 0);
		// 上位バイトが 3 (UNIX) のときだけ、展開側が external attributes をパーミッション
		// として読む。ここが 0 (FAT) だと 0755 は無視される。
		central.writeUInt16LE(0x031e, 4); // version made by: UNIX, 3.0
		central.writeUInt16LE(20, 6);
		central.writeUInt16LE(0, 8);
		central.writeUInt16LE(0, 10);
		central.writeUInt16LE(0, 12);
		central.writeUInt16LE(0x0021, 14);
		central.writeUInt32LE(crc, 16);
		central.writeUInt32LE(entry.data.length, 20);
		central.writeUInt32LE(entry.data.length, 24);
		central.writeUInt16LE(name.length, 28);
		central.writeUInt16LE(0, 30); // extra
		central.writeUInt16LE(0, 32); // comment
		central.writeUInt16LE(0, 34); // disk
		central.writeUInt16LE(0, 36); // internal attributes
		// 上位 16 bit が UNIX のモード。<< 16 だと符号付き 32 bit を溢れるので掛ける。
		central.writeUInt32LE((0o100000 | entry.mode) * 0x10000, 38); // external attributes
		central.writeUInt32LE(offset, 42);

		locals.push(local, name, entry.data);
		centrals.push(central, name);
		offset += local.length + name.length + entry.data.length;
	}

	const centralSize = centrals.reduce((total, chunk) => total + chunk.length, 0);
	const end = Buffer.alloc(22);
	end.writeUInt32LE(0x06054b50, 0);
	end.writeUInt16LE(0, 4); // disk
	end.writeUInt16LE(0, 6); // disk with the central directory
	end.writeUInt16LE(entries.length, 8);
	end.writeUInt16LE(entries.length, 10);
	end.writeUInt32LE(centralSize, 12);
	end.writeUInt32LE(offset, 16);
	end.writeUInt16LE(0, 20); // comment

	return Buffer.concat([...locals, ...centrals, end]);
}

function buildInstallers(outDir) {
	const payload = Buffer.from(buildPlugin(), "utf8");

	fs.mkdirSync(outDir, { recursive: true });

	const pluginPath = path.join(outDir, DEFAULT_PLUGIN_FILE);
	const windowsPath = path.join(outDir, WINDOWS_INSTALLER_NAME);
	const macPath = path.join(outDir, MACOS_INSTALLER_NAME);
	const macArchivePath = path.join(outDir, MACOS_ARCHIVE_NAME);
	const macInstaller = Buffer.from(buildMacInstaller(payload), "utf8");

	fs.writeFileSync(pluginPath, payload);
	fs.writeFileSync(windowsPath, buildWindowsInstaller(payload));
	fs.writeFileSync(macPath, macInstaller, { mode: 0o755 });
	fs.writeFileSync(macArchivePath, createZip([{ name: MACOS_INSTALLER_NAME, data: macInstaller, mode: 0o755 }]));

	return { pluginPath, windowsPath, macPath, macArchivePath };
}

if (require.main === module) {
	const outDir = path.resolve(process.cwd(), process.argv[2] || "dist");
	const built = buildInstallers(outDir);
	for (const filePath of [built.pluginPath, built.windowsPath, built.macArchivePath]) {
		console.log(`${path.relative(process.cwd(), filePath)} (${fs.statSync(filePath).size} bytes)`);
	}
}

module.exports = {
	MACOS_ARCHIVE_NAME,
	MACOS_INSTALLER_NAME,
	PAYLOAD_MARKER,
	WINDOWS_INSTALLER_NAME,
	buildInstallers,
	buildMacInstaller,
	buildWindowsInstaller,
	createZip,
};
